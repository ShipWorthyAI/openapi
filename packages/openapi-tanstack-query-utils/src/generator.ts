import type { Generator, ParsedOpenApi } from "@shipworthy/openapi-parser";
import type { OperationRoute } from "./query-utils";

const blockedOperationIds = new Set(["__proto__", "constructor", "prototype"]);

/** operationId → [METHOD, path]. Every operation needs an id. */
export function operationRoutes(model: ParsedOpenApi): Record<string, OperationRoute> {
  const routes: Record<string, OperationRoute> = Object.create(null);

  for (const operation of model.operations) {
    const label = `${operation.method} ${operation.path}`;
    const id = operation.operationId;
    if (!id) throw new Error(`${label}: Missing operationId`);
    if (blockedOperationIds.has(id)) throw new Error(`Unsupported operationId: ${id}`);
    if (Object.hasOwn(routes, id)) throw new Error(`Duplicate operationId: ${id}`);
    routes[id] = [operation.method as OperationRoute[0], operation.path];
  }

  return routes;
}

export const tanstackQuery: Generator<string> = {
  id: "tanstack-query",
  generate(model, options) {
    const prefix = typeof options.prefix === "string" ? options.prefix : "";
    const name = typeof options.name === "string" ? options.name : prefix;
    return clientSource(prefix, name, operationRoutes(model));
  },
};

export function clientSource(
  prefix: string,
  name: string,
  routes: Record<string, OperationRoute>,
): string {
  const entries = Object.entries(routes)
    .map(([id, route]) => `  ${JSON.stringify(id)}: ${JSON.stringify(route)},`)
    .join("\n");

  return `// Generated by openapi-react-query. Do not edit.
import { createApiClient, createTanstackQueryUtils, type TanstackQueryUtilsOptions } from "@shipworthy/openapi-tanstack-query-utils";
import type { ${prefix}ApiPaths, ${prefix}ApiOperations } from "./types";

export type { ${prefix}ApiPaths, ${prefix}ApiComponents, ${prefix}ApiOperations } from "./types";
export const create${prefix}ApiClient: typeof createApiClient<${prefix}ApiPaths> = createApiClient<${prefix}ApiPaths>;
export type ${prefix}ApiClient = ReturnType<typeof create${prefix}ApiClient>;

const routes = {
${entries}
} as const;

export function create${prefix}ApiQueryUtils(client: ${prefix}ApiClient, options?: Partial<TanstackQueryUtilsOptions>) {
  return createTanstackQueryUtils<Pick<${prefix}ApiOperations, keyof typeof routes>>(client, routes, { prefix: ${JSON.stringify(
    name,
  )}, ...options });
}
`;
}

const hooks = ["Query", "QueryOptions", "SuspenseQuery", "InfiniteQuery", "Mutation"] as const;

/** React Query client printed from the generated paths type. */
export function reactQueryClientSource(prefix: string): string {
  const paths = `${prefix}ApiPaths`;

  return `// Generated by openapi-react-query. Do not edit.
import {
  createApiClient,
  useApiClient,
${hooks.map((hook) => `  useApiClient${hook},`).join("\n")}
} from "@shipworthy/openapi-react-query";
import type { ${paths} } from "./types";

export type { ${paths}, ${prefix}ApiComponents, ${prefix}ApiOperations } from "./types";
export { ApiClientProvider as ${prefix}ApiClientProvider } from "@shipworthy/openapi-react-query";

export const create${prefix}ApiClient: typeof createApiClient<${paths}> = createApiClient<${paths}>;
export type ${prefix}ApiClient = ReturnType<typeof create${prefix}ApiClient>;
export const use${prefix}ApiClient: typeof useApiClient<${paths}> = useApiClient<${paths}>;

${hooks
  .map(
    (hook) => `export const use${prefix}${hook}: ReturnType<typeof useApiClient${hook}<${paths}>> =
  useApiClient${hook}<${paths}>();`,
  )
  .join("\n")}
`;
}
