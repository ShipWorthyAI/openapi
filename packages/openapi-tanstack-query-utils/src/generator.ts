import type { OperationRoute } from "./query-utils";
import { openapiTS, ts, type OpenAPI3 } from "@shipworthy/openapi-typescript-api";

const methods = ["get", "put", "post", "delete", "options", "head", "patch", "trace"] as const;

/** Types stay in the AST; only operation names, methods and paths become runtime data. */
export async function generateSchema(source: URL | OpenAPI3) {
  // A default does not make a property required.
  const nodes = await openapiTS(source, { defaultNonNullable: false });
  const declarations = new Map(
    nodes.flatMap((node) =>
      ts.isInterfaceDeclaration(node) || ts.isTypeAliasDeclaration(node)
        ? [[node.name.text, node] as const]
        : [],
    ),
  );
  function members(node: ts.Node | undefined): readonly ts.TypeElement[] {
    if (!node) return [];
    if (ts.isInterfaceDeclaration(node) || ts.isTypeLiteralNode(node)) return node.members;
    if (ts.isTypeAliasDeclaration(node)) return members(node.type);
    if (ts.isTypeReferenceNode(node) && ts.isIdentifier(node.typeName))
      return members(declarations.get(node.typeName.text));
    if (
      ts.isIndexedAccessTypeNode(node) &&
      ts.isLiteralTypeNode(node.indexType) &&
      ts.isStringLiteral(node.indexType.literal)
    ) {
      const name = node.indexType.literal.text;
      const property = members(node.objectType).find(
        (member) =>
          ts.isPropertySignature(member) && "text" in member.name && member.name.text === name,
      );
      return members(property && ts.isPropertySignature(property) ? property.type : undefined);
    }
    return [];
  }
  const routes: Record<string, OperationRoute> = Object.create(null);
  for (const route of members(declarations.get("paths"))) {
    if (!ts.isPropertySignature(route) || !ts.isStringLiteral(route.name)) continue;
    for (const member of members(route.type)) {
      if (!ts.isPropertySignature(member)) continue;
      const method = methods.find((method) => "text" in member.name && method === member.name.text);
      if (!method || !member.type || member.type.kind === ts.SyntaxKind.NeverKeyword) continue;
      const type = member.type;
      if (
        !ts.isIndexedAccessTypeNode(type) ||
        !ts.isLiteralTypeNode(type.indexType) ||
        !ts.isStringLiteral(type.indexType.literal)
      )
        throw new Error(`${method.toUpperCase()} ${route.name.text}: Missing operationId`);
      const id = type.indexType.literal.text;
      if (["__proto__", "constructor", "prototype"].includes(id))
        throw new Error(`Unsupported operationId: ${id}`);
      routes[id] = [method.toUpperCase() as OperationRoute[0], route.name.text];
    }
  }
  return { nodes, routes };
}

export function clientSource(
  prefix: string,
  name: string,
  routes: Record<string, OperationRoute>,
): string {
  const entries = Object.entries(routes)
    .map(([id, route]) => `  ${JSON.stringify(id)}: ${JSON.stringify(route)},`)
    .join("\n");
  return `// Generated by openapi-react-query. Do not edit.
import { createApiClient, createTanstackQueryUtils, type TanstackQueryUtilsOptions } from "@shipworthy/openapi-tanstack-query-utils";
import type { ${prefix}ApiPaths, ${prefix}ApiOperations } from "./types";

export type { ${prefix}ApiPaths, ${prefix}ApiComponents, ${prefix}ApiOperations } from "./types";
export const create${prefix}ApiClient: typeof createApiClient<${prefix}ApiPaths> = createApiClient<${prefix}ApiPaths>;
export type ${prefix}ApiClient = ReturnType<typeof create${prefix}ApiClient>;

const routes = {
${entries}
} as const;

export function create${prefix}ApiQueryUtils(client: ${prefix}ApiClient, options?: Partial<TanstackQueryUtilsOptions>) {
  return createTanstackQueryUtils<Pick<${prefix}ApiOperations, keyof typeof routes>>(client, routes, { prefix: ${JSON.stringify(
    name,
  )}, ...options });
}
`;
}
