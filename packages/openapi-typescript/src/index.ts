export const COMMENT_HEADER = `/**
 * This file was auto-generated by openapi-typescript.
 * Do not make direct changes to the file.
 */

`;

function pascalCase(value: string): string {
  return value.replace(/(?:^|[-_])([a-zA-Z0-9])/g, (_, letter: string) => letter.toUpperCase());
}

/** Rename generated top-level declarations and the references that point at them. */
export function prefixTypes(nodes: readonly ts.Node[], prefix: string): string {
  const names = new Map<string, string>();

  for (const node of nodes) {
    if (ts.isInterfaceDeclaration(node) || ts.isTypeAliasDeclaration(node)) {
      names.set(node.name.text, `${prefix}Api${pascalCase(node.name.text.replace(/^\$/, ""))}`);
    }
  }

  const result = ts.transform(
    [...nodes],
    [
      () => {
        const visit: ts.Visitor = (node) => {
          const name =
            ts.isInterfaceDeclaration(node) || ts.isTypeAliasDeclaration(node)
              ? node.name
              : ts.isTypeReferenceNode(node) && ts.isIdentifier(node.typeName)
                ? node.typeName
                : undefined;

          const replacement = name && names.get(name.text);

          return ts.visitEachChild(node, (child) =>
            child === name && replacement ? ts.factory.createIdentifier(replacement) : visit(child),
          );
        };

        return (node) => ts.visitNode(node, visit) as ts.Node;
      },
    ],
  );

  try {
    return COMMENT_HEADER + astToString(result.transformed);
  } finally {
    result.dispose();
  }
}

const optionalBoolean = Schema.optionalKey(Schema.Boolean);

const PluginOptions = Schema.Struct({
  additionalProperties: optionalBoolean,
  alphabetize: optionalBoolean,
  arrayLength: optionalBoolean,
  emptyObjectsUnknown: optionalBoolean,
  cwd: Schema.optionalKey(Schema.Unknown),
  defaultNonNullable: optionalBoolean,
  excludeDeprecated: optionalBoolean,
  transform: Schema.optionalKey(Schema.Unknown),
  postTransform: Schema.optionalKey(Schema.Unknown),
  transformProperty: Schema.optionalKey(Schema.Unknown),
  immutable: optionalBoolean,
  silent: optionalBoolean,
  version: Schema.optionalKey(Schema.Finite),
  exportType: optionalBoolean,
  enum: optionalBoolean,
  enumValues: optionalBoolean,
  conditionalEnums: optionalBoolean,
  dedupeEnums: optionalBoolean,
  pathParamsAsTypes: optionalBoolean,
  propertiesRequiredByDefault: optionalBoolean,
  rootTypes: optionalBoolean,
  rootTypesNoSchemaPrefix: optionalBoolean,
  rootTypesKeepCasing: optionalBoolean,
  inject: Schema.optionalKey(Schema.String),
  makePathsEnum: optionalBoolean,
  generatePathParams: optionalBoolean,
  readWriteMarkers: optionalBoolean,
});

function callback<A>(value: unknown): A | undefined {
  return Predicate.isFunction(value) ? (value as A) : undefined;
}

/** TypeScript plugin. `generate` prints `paths`, `webhooks`, `components`, and `operations`. */
export const typescript: Generator<ts.Node[], TypegenError> = {
  id: "typescript",
  generate: Effect.fnUntraced(function* (
    model: ParsedOpenApi,
  ): Effect.fn.Return<ts.Node[], TypegenError> {
    const options = yield* Schema.decodeEffect(PluginOptions)(raw).pipe(
      Effect.mapError((cause) => new TypegenError({ message: cause.message })),
    );


    const ctx: GlobalContext = {
      additionalProperties: options.additionalProperties ?? false,
      alphabetize: options.alphabetize ?? false,
      arrayLength: options.arrayLength ?? false,
      defaultNonNullable: options.defaultNonNullable ?? true,
      discriminators: scanDiscriminators(model, options as OpenAPITSOptions),
      emptyObjectsUnknown: options.emptyObjectsUnknown ?? false,
      enum: options.enum ?? false,
      enumValues: options.enumValues ?? false,
      conditionalEnums: options.conditionalEnums ?? false,
      dedupeEnums: options.dedupeEnums ?? false,
      excludeDeprecated: options.excludeDeprecated ?? false,
      exportType: options.exportType ?? false,
      immutable: options.immutable ?? false,
      rootTypes: options.rootTypes ?? false,
      rootTypesNoSchemaPrefix: options.rootTypesNoSchemaPrefix ?? false,
      rootTypesKeepCasing: options.rootTypesKeepCasing ?? false,
      injectFooter: [],
      pathParamsAsTypes: options.pathParamsAsTypes ?? false,
      postTransform: callback(options.postTransform),
      propertiesRequiredByDefault: options.propertiesRequiredByDefault ?? false,
      silent: options.silent ?? false,
      inject: options.inject,
      transform: callback(options.transform),
      transformProperty: callback(options.transformProperty),
      makePathsEnum: options.makePathsEnum ?? false,
      generatePathParams: options.generatePathParams ?? false,
      readWriteMarkers: options.readWriteMarkers ?? false,
      resolve($ref) {
        return resolveRef(model, $ref, { silent: options.silent ?? false });
      },
    };

    const transformT = performance.now();

    return yield* Effect.try({
      try: () => {
        const result = transformSchema(model, ctx);

        debug(
          "Completed AST transformation for entire document",
          "ts",
          performance.now() - transformT,
        );

        return result;
      },
      catch: (cause) =>
        cause instanceof TypegenError
          ? cause
          : new TypegenError({
              message: Predicate.isError(cause) ? cause.message : String(cause),
            }),
    });
  }),
};
