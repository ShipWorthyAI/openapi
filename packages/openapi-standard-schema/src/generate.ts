import type { Generator } from "@shipworthy/openapi-generator";
import type { ParsedService } from "@shipworthy/openapi-transformer";
import { Effect, JsonPointer, JsonSchema, Predicate, Schema, SchemaRepresentation } from "effect";
import { SchemaGenerationError } from "./errors.js";

const header = "// Generated by openapi-standard-schema. Do not edit.\n";
const identifierPattern = /[A-Za-z_$][A-Za-z0-9_$]*/g;

type Pool = Record<string, JsonSchema.JsonSchema>;

export const standardSchema: Generator<string, SchemaGenerationError> = {
  id: "standard-schema",
  generate: Effect.fnUntraced(function* (
    model: ParsedService,
  ): Effect.fn.Return<string, SchemaGenerationError> {
    return yield* Effect.try({
      try: () => render(model),
      catch: failure,
    });
  }),
};

function failure(cause: unknown): SchemaGenerationError {
  if (Schema.is(SchemaGenerationError)(cause)) return cause;

  return new SchemaGenerationError({
    message: Predicate.isError(cause) ? cause.message : String(cause),
    cause,
  });
}

function render(model: ParsedService): string {
  const names = Object.keys(model.components.schemas);
  const document = assemble(model, names);
  if (!document) return header;

  const imported = SchemaRepresentation.fromJsonSchemaMultiDocument(document, {
    patterns: "apply",
  });

  const asts = nonEmpty(imported.map((schema) => schema.ast));
  if (!asts) return header;

  const code = SchemaRepresentation.toCodeDocument(SchemaRepresentation.toRepresentations(asts));
  return emit(names, code);
}

function assemble(
  model: ParsedService,
  names: readonly string[],
): JsonSchema.MultiDocument<"draft-2020-12"> | undefined {
  if (names.length === 0) return undefined;

  const componentNames = new Set(names);
  const rootKeys = rootDefinitionKeys(model.$defs, componentNames);
  const rootRenames = new Map([...rootKeys].filter(([name, key]) => name !== key));

  const pool: Pool = {};

  const convertedComponents = names.map((name) =>
    fromOpenApi(
      prepare(
        model.components.schemas[name],
        `#/components/schemas/${name}`,
        componentNames,
        rootRenames,
      ),
    ),
  );

  names.forEach((name, index) => {
    const converted = convertedComponents[index];
    if (converted) pool[name] = converted.schema;
  });

  const convertedRoots = Object.entries(model.$defs).map(([name, schema]) => ({
    name,
    key: rootKeys.get(name) ?? name,
    converted: fromOpenApi(prepare(schema, `#/$defs/${name}`, componentNames, rootRenames)),
  }));

  for (const { name, key, converted } of convertedRoots) {
    const component = pool[name];

    if (key !== name && component !== undefined && sameSchema(component, converted.schema)) {
      const target = componentToken(name);
      for (const schema of Object.values(pool)) rewriteDefKey(schema, key, target);
      rewriteDefKey(converted.schema, key, target);
      for (const schema of Object.values(converted.definitions)) rewriteDefKey(schema, key, target);

      for (const other of convertedRoots) {
        rewriteDefKey(other.converted.schema, key, target);
        for (const schema of Object.values(other.converted.definitions))
          rewriteDefKey(schema, key, target);
      }
    } else {
      pool[key] = converted.schema;
    }
  }

  for (const converted of convertedComponents)
    mergeDefinitions(pool, converted.definitions, converted.schema);

  for (const { converted } of convertedRoots) {
    mergeDefinitions(pool, converted.definitions, converted.schema);
  }

  const bindings = bindComponents(pool, names);
  const schemas = nonEmpty(names.map((name) => ({ $ref: defRef(binding(bindings, name)) })));
  if (!schemas) return undefined;
  return { dialect: "draft-2020-12", schemas, definitions: pool };
}

function binding(bindings: ReadonlyMap<string, string>, name: string): string {
  const value = bindings.get(name);
  if (value === undefined)
    throw new SchemaGenerationError({ message: `Missing binding for ${name}` });
  return value;
}

function rootDefinitionKeys(
  defs: Readonly<Record<string, unknown>>,
  componentNames: ReadonlySet<string>,
): Map<string, string> {
  const used = new Set(componentNames);
  const keys = new Map<string, string>();

  for (const name of Object.keys(defs)) {
    const key = used.has(name) ? uniqueAgainst(used, name) : name;
    used.add(key);
    keys.set(name, key);
  }

  return keys;
}

function prepare(
  value: unknown,
  path: string,
  componentNames: ReadonlySet<string>,
  rootRenames: ReadonlyMap<string, string>,
): JsonSchema.JsonSchema {
  const schema = normalize(value, path);
  retargetComponentRefs(schema, componentNames);
  retargetRootDefRefs(schema, rootRenames);
  return schema;
}

function normalize(value: unknown, path: string): JsonSchema.JsonSchema {
  if (Predicate.isBoolean(value)) return value ? {} : { not: {} };

  if (!Predicate.isObject(value)) {
    throw new SchemaGenerationError({ message: `${path}: expected a JSON schema` });
  }

  return structuredClone(value) as JsonSchema.JsonSchema;
}

/** The parser converts every schema to Draft 2020-12 with OpenAPI component refs, which is the 3.1 dialect. */
function fromOpenApi(schema: JsonSchema.JsonSchema) {
  return JsonSchema.fromSchemaOpenApi3_1(schema);
}

function mergeDefinitions(
  pool: Pool,
  extra: JsonSchema.Definitions,
  owner: JsonSchema.JsonSchema,
): void {
  for (const [name, schema] of Object.entries(extra)) {
    if (!Object.hasOwn(pool, name)) {
      pool[name] = schema;
      continue;
    }

    if (sameSchema(pool[name], schema)) continue;
    const unique = uniqueAgainst(new Set(Object.keys(pool)), name);
    pool[unique] = schema;
    rewriteDefKey(owner, name, unique);
    rewriteDefKey(schema, name, unique);
  }
}

function bindComponents(pool: Pool, names: readonly string[]): Map<string, string> {
  const used = new Set(Object.keys(pool));
  const bindings = new Map<string, string>();

  for (const name of names) {
    let candidate = `${name}Schema`;
    while (used.has(candidate)) candidate += "Schema";
    used.add(candidate);
    bindings.set(name, candidate);
  }

  const replacements = new Map<string, string>();
  for (const [name, binding] of bindings) replacements.set(componentToken(name), binding);

  const next: Pool = {};
  for (const [key, schema] of Object.entries(pool)) next[bindings.get(key) ?? key] = schema;
  for (const key of Object.keys(pool)) delete pool[key];
  Object.assign(pool, next);
  for (const schema of Object.values(pool)) rewriteDefKeys(schema, replacements);
  return bindings;
}

/** Keeps a component ref distinct from a `$defs` entry of the same name until bindings are assigned. */
function componentToken(name: string): string {
  return `\u0000${name}`;
}

function defRef(name: string): string {
  return JsonPointer.formatUriFragment(["$defs", name]);
}

function retargetComponentRefs(schema: unknown, names: ReadonlySet<string>): void {
  visit(schema, (record) => {
    if (!Predicate.isString(record.$ref)) return;
    const path = JsonPointer.parseUriFragment(record.$ref);
    const name = path?.[2];

    if (
      path?.length === 3 &&
      path[0] === "components" &&
      path[1] === "schemas" &&
      name &&
      names.has(name)
    ) {
      record.$ref = defRef(componentToken(name));
    }
  });
}

function retargetRootDefRefs(schema: unknown, renames: ReadonlyMap<string, string>): void {
  const local =
    Predicate.isObject(schema) && Predicate.isObject(schema.$defs) ? schema.$defs : undefined;

  visit(schema, (record) => {
    if (!Predicate.isString(record.$ref)) return;
    const path = JsonPointer.parseUriFragment(record.$ref);
    const name = path?.[1];
    if (path?.length !== 2 || path[0] !== "$defs" || name === undefined) return;
    const target = renames.get(name);
    if (target === undefined || (local !== undefined && Object.hasOwn(local, name))) return;
    record.$ref = defRef(target);
  });
}

function rewriteDefKey(schema: unknown, from: string, to: string): void {
  rewriteDefKeys(schema, new Map([[from, to]]));
}

function rewriteDefKeys(schema: unknown, replacements: ReadonlyMap<string, string>): void {
  visit(schema, (record) => {
    if (!Predicate.isString(record.$ref)) return;
    const path = JsonPointer.parseUriFragment(record.$ref);
    const name = path?.[1];
    if (path === undefined || path.length < 2 || path[0] !== "$defs" || name === undefined) return;
    const next = replacements.get(name);
    if (next === undefined) return;
    record.$ref = JsonPointer.formatUriFragment(["$defs", next, ...path.slice(2)]);
  });
}

function visit(schema: unknown, onObject: (record: Record<string, unknown>) => void): void {
  if (Array.isArray(schema)) {
    for (const item of schema) visit(item, onObject);
    return;
  }

  if (!Predicate.isObject(schema)) return;
  onObject(schema);
  for (const value of Object.values(schema)) visit(value, onObject);
}

function sameSchema(
  left: JsonSchema.JsonSchema | undefined,
  right: JsonSchema.JsonSchema,
): boolean {
  return JSON.stringify(left) === JSON.stringify(right);
}

function uniqueAgainst(used: ReadonlySet<string>, name: string): string {
  let suffix = 2;
  let candidate = `${name}_${suffix}`;
  while (used.has(candidate)) candidate = `${name}_${++suffix}`;
  return candidate;
}

function nonEmpty<A>(values: readonly A[]): [A, ...A[]] | undefined {
  const [first, ...rest] = values;
  if (first === undefined && values.length === 0) return undefined;
  return [first as A, ...rest];
}

function emit(names: readonly string[], code: SchemaRepresentation.CodeDocument): string {
  const imports = code.artifacts.flatMap((artifact) =>
    artifact._tag === "Import" ? [artifact.importDeclaration] : [],
  );

  if (!imports.some((line) => line.includes("Schema")))
    imports.unshift(`import { Schema } from "effect";`);

  const artifacts = code.artifacts.flatMap((artifact) => {
    if (artifact._tag === "Enum") return [artifact.code.runtime];
    if (artifact._tag === "Symbol")
      return [`const ${artifact.identifier} = ${artifact.code.runtime};`];
    return [];
  });

  const nonRecursives = code.references.nonRecursives;
  const recursives = Object.entries(code.references.recursives);

  const types = [
    ...nonRecursives.map(({ $ref, code: body }) => `type ${$ref} = ${body.Type};`),
    ...recursives.map(([name, body]) => `type ${name} = ${body.Type};`),
  ];

  const forward = forwardReferenced(nonRecursives, recursives);

  const used = new Set<string>([
    ...nonRecursives.map(({ $ref }) => $ref),
    ...recursives.map(([name]) => name),
    ...names,
  ]);

  const internals = new Map<string, string>();
  for (const name of forward) internals.set(name, recursiveInternalName(name, used));

  const declarations = [...forward].map((name) => {
    const internal = internals.get(name);
    return `const ${name} = Schema.suspend((): Schema.Codec<${name}> => ${internal});`;
  });

  const bodies = nonRecursives.map(({ $ref, code: body }) => `const ${$ref} = ${body.runtime};`);

  for (const [name, body] of recursives) {
    const internal = internals.get(name);
    bodies.push(`const ${internal ?? name} = ${body.runtime};`);
  }

  const exports = names.flatMap((name, index) => {
    const body = code.codes[index];
    if (!body) throw new SchemaGenerationError({ message: `Missing generated schema for ${name}` });

    return [
      `export type ${name} = ${body.Type};`,
      `export const ${name} = Schema.toStandardSchemaV1(${body.runtime});`,
    ];
  });

  return `${header}${[...imports, ...artifacts, ...types, ...declarations, ...bodies, ...exports].join("\n")}\n`;
}

function forwardReferenced(
  nonRecursives: readonly { readonly code: SchemaRepresentation.Code }[],
  recursives: readonly (readonly [string, SchemaRepresentation.Code])[],
): Set<string> {
  const names = new Set(recursives.map(([name]) => name));
  const indexes = new Map(recursives.map(([name], index) => [name, index]));
  const referenced = new Set<string>();

  const scan = (runtime: string, accept: (name: string) => boolean) => {
    for (const match of runtime.matchAll(identifierPattern)) {
      const name = match[0];
      if (name !== undefined && names.has(name) && accept(name)) referenced.add(name);
    }
  };

  for (const { code } of nonRecursives) scan(code.runtime, () => true);

  for (const [index, entry] of recursives.entries()) {
    const body = entry[1];
    scan(body.runtime, (name) => (indexes.get(name) ?? -1) > index);
  }

  return referenced;
}

function recursiveInternalName(name: string, used: Set<string>): string {
  let candidate = `__recursive_${name}`;
  while (used.has(candidate)) candidate = `_${candidate}`;
  used.add(candidate);
  return candidate;
}
