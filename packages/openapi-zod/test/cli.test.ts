import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { existsSync } from "node:fs";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { test } from "node:test";
import { promisify } from "node:util";

const exec = promisify(execFile);
const cli = resolve(import.meta.dirname, "../../openapi-cli/src/bin.ts");

const schema = {
  openapi: "3.1.0",
  info: { title: "Fixture", version: "1" },
  paths: {
    "/items": {
      post: {
        operationId: "createItem",
        requestBody: {
          required: true,
          content: {
            "application/json": {
              schema: { $ref: "#/components/schemas/Item" },
            },
          },
        },
        responses: { "204": { description: "Created" } },
      },
    },
  },
  components: {
    schemas: {
      Item: {
        type: "object",
        required: ["name"],
        properties: {
          name: { type: "string" },
          count: { type: "integer", default: 1 },
        },
      },
    },
  },
};

/** snake_case fields without a discriminator. */
const snakeSchema = {
  openapi: "3.1.0",
  info: { title: "Fixture", version: "1" },
  paths: {
    "/reservations": {
      post: {
        operationId: "createReservation",
        requestBody: {
          required: true,
          content: {
            "application/json": {
              schema: { $ref: "#/components/schemas/ReservationInput" },
            },
          },
        },
        responses: { "204": { description: "Created" } },
      },
    },
  },
  components: {
    schemas: {
      ReservationInput: {
        type: "object",
        required: ["party_size", "guest_name"],
        properties: {
          party_size: { type: "integer" },
          guest_name: { type: "string" },
          special_requests: { type: "string" },
        },
      },
    },
  },
};

/** A mapped `oneOf` discriminator, which makes the generator emit its issue-reporting helper. */
const discriminatorSchema = {
  openapi: "3.1.0",
  info: { title: "Fixture", version: "1" },
  paths: {},
  components: {
    schemas: {
      Cat: {
        type: "object",
        required: ["kind", "lives"],
        properties: { kind: { type: "string" }, lives: { type: "integer" } },
      },
      Dog: {
        type: "object",
        required: ["kind", "breed"],
        properties: { kind: { type: "string" }, breed: { type: "string" } },
      },
      Pet: {
        oneOf: [{ $ref: "#/components/schemas/Cat" }, { $ref: "#/components/schemas/Dog" }],
        discriminator: {
          propertyName: "kind",
          mapping: { cat: "#/components/schemas/Cat", dog: "#/components/schemas/Dog" },
        },
      },
    },
  },
};

/** Generates `plugins` for `spec` into `<directory>/fixture`, then type-checks `consumer`. */
async function generateAndTypeCheck(
  spec: object,
  args: readonly string[],
  check: (files: { schemas: string; types: string }) => void,
  consumer: string,
) {
  const directory = await mkdtemp(resolve(import.meta.dirname, ".generation-"));
  const input = resolve(directory, "schema.json");
  await writeFile(input, JSON.stringify(spec));

  try {
    await exec("bun", [
      "run",
      cli,
      "generate",
      "zod",
      "-i",
      input,
      "-o",
      resolve(directory, "fixture"),
      ...args,
    ]);

    check({
      schemas: await readFile(resolve(directory, "fixture/zod-schema.ts"), "utf8"),
      types: await readFile(resolve(directory, "fixture/types.ts"), "utf8"),
    });

    await writeFile(resolve(directory, "consumer.ts"), consumer);

    const compilers = [
      resolve(import.meta.dirname, "../node_modules/typescript/bin/tsc"),
      resolve(import.meta.dirname, "../../../node_modules/typescript/bin/tsc"),
    ].filter((path) => existsSync(path));

    assert.ok(compilers.length > 0);

    for (const compiler of compilers) {
      await exec(process.execPath, [
        compiler,
        "--ignoreConfig",
        "--noEmit",
        "--strict",
        "--skipLibCheck",
        "--target",
        "ES2022",
        "--module",
        "ESNext",
        "--moduleResolution",
        "bundler",
        resolve(directory, "consumer.ts"),
      ]);
    }
  } finally {
    await rm(directory, { recursive: true, force: true });
  }
}

void test("CLI writes types and Zod validators", async () => {
  await generateAndTypeCheck(
    schema,
    [],
    ({ schemas, types }) => {
      assert.match(
        schemas,
        /^\/\*\*\n \* This file was auto-generated by @shipworthy\/openapi-zod\./,
      );

      assert.match(schemas, /^ \* @shipworthy\/openapi-zod@[^:]+:[0-9a-f]{64}$/m);
      assert.match(schemas, /export const Item/);
      assert.match(schemas, /import type \{ components, operations \} from "\.\/types";/);
      assert.match(schemas, /export const createItemRequestBody/);
      assert.match(types, /export interface components/);
    },
    `
      import { Item, createItemRequestBody } from "./fixture/zod-schema";
      import type { components } from "./fixture/types";
      const item: components["schemas"]["Item"] = Item.parse({ name: "Hotel" });
      const body: { name: string } = createItemRequestBody.parse({ name: "Hotel" });
      void item;
      void body;
      const name: components["schemas"]["Item"]["name"] = "Hotel";
      void name;
    `,
  );
});

void test("CLI writes camelCase Zod validators that parse into camelCase types", async () => {
  await generateAndTypeCheck(
    snakeSchema,
    ["--camel-case"],
    ({ schemas, types }) => {
      assert.match(schemas, /^ \* Field casing: camelCase$/m);
      assert.match(types, /^ \* Field casing: camelCase$/m);
      assert.match(schemas, /"partySize"/);
      assert.doesNotMatch(schemas, /party_size/);
      assert.match(types, /partySize: number;/);
    },
    `
      import { ReservationInput, createReservationRequestBody } from "./fixture/zod-schema";
      import type { components } from "./fixture/types";
      const input: components["schemas"]["ReservationInput"] = ReservationInput.parse({
        partySize: 2,
        guestName: "Ada",
        specialRequests: "Window seat",
      });
      const body: components["schemas"]["ReservationInput"] = createReservationRequestBody.parse({
        partySize: 2,
        guestName: "Ada",
      });
      void input;
      void body;
    `,
  );
});

void test("CLI writes a discriminator helper that type-checks in strict mode", async () => {
  await generateAndTypeCheck(
    discriminatorSchema,
    [],
    ({ schemas }) => {
      assert.match(schemas, /function __openapiDiscriminatorIssues\(/);
    },
    `
      import { Pet } from "./fixture/zod-schema";
      import type { components } from "./fixture/types";
      const pet: components["schemas"]["Pet"] = Pet.parse({ kind: "cat", lives: 9 });
      void pet;
    `,
  );
});
