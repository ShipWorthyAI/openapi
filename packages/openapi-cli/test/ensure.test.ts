import { cpSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { test, type TestContext } from "vitest";
import { workspace } from "./cli.ts";

const stampLine = /^ \* (@shipworthy\/openapi-typescript@\S+:[0-9a-f]{64})$/m;

const spec = (title: string) =>
  JSON.stringify({
    openapi: "3.1.0",
    info: { title, version: "1.0.0" },
    paths: {
      "/pets": {
        get: {
          operationId: "listPets",
          responses: { "200": { description: "OK" } },
        },
      },
    },
  });

const header = (name: string) =>
  new RegExp(
    `^/\\*\\*\\n \\* This file was auto-generated by ${name}\\.\\n \\* Do not make direct changes to the file\\.\\n \\*\\n \\* ${name}@0\\.0\\.2:[0-9a-f]{64}\\n \\*/\\n\\n`,
  );

function setup(context: TestContext) {
  const cli = workspace(context);
  writeFileSync(join(cli.dir, "a.json"), spec("Pets"));
  const typesPath = join(cli.dir, "out/pets/types.ts");
  const types = () => readFileSync(typesPath, "utf8");

  return {
    ...cli,
    types,
    stamp: () => stampLine.exec(types())?.[1],
    mark: () => writeFileSync(typesPath, `${types()}// marker\n`),
    isMarked: () => types().includes("// marker"),
    generate: (input: string, ...flags: string[]) =>
      cli.ok("generate", "tanstack-query", input, "-o", "out", "--name", "pets", ...flags),
  };
}

test("records each generator's version and the schema hash in the comment header", async (context) => {
  const { expect } = context;
  const cli = setup(context);
  await cli.generate("a.json");
  expect(cli.types()).toMatch(header("@shipworthy/openapi-typescript"));
  expect(cli.types()).toContain("}\n\nexport type webhooks");

  expect(readFileSync(join(cli.dir, "out/pets/client.ts"), "utf8")).toMatch(
    header("@shipworthy/openapi-tanstack-query"),
  );
});

test("skips types.ts when the contents match, wherever the source lives", async (context) => {
  const { expect } = context;
  const cli = setup(context);
  await cli.generate("a.json");
  const stamp = cli.stamp();
  cli.mark();
  mkdirSync(join(cli.dir, "elsewhere"));
  cpSync(join(cli.dir, "a.json"), join(cli.dir, "elsewhere/b.json"));
  await cli.generate(join(cli.dir, "elsewhere/b.json"));
  expect(cli.isMarked()).toBe(true);
  expect(cli.stamp()).toBe(stamp);
});

test("regenerates types.ts when the contents change", async (context) => {
  const { expect } = context;
  const cli = setup(context);
  await cli.generate("a.json");
  const stamp = cli.stamp();
  cli.mark();
  writeFileSync(join(cli.dir, "a.json"), spec("More pets"));
  await cli.generate("a.json");
  expect(cli.isMarked()).toBe(false);
  expect(cli.stamp()).not.toBe(stamp);
});

test("--force regenerates types.ts when the contents match", async (context) => {
  const { expect } = context;
  const cli = setup(context);
  await cli.generate("a.json");
  const stamp = cli.stamp();
  cli.mark();
  await cli.generate("a.json", "--force");
  expect(cli.isMarked()).toBe(false);
  expect(cli.stamp()).toBe(stamp);
});

test("typescript and standard-schema outputs carry a stamped header", async (context) => {
  const { expect } = context;
  const cli = setup(context);

  const [typescript, standardSchema, stdin] = await Promise.all([
    cli.ok("generate", "typescript", "a.json"),
    cli.ok("generate", "standard-schema", "a.json"),
    cli.run(["generate", "typescript"], { stdin: spec("Pets") }),
  ]);

  expect(typescript).toMatch(header("@shipworthy/openapi-typescript"));
  expect(standardSchema).toMatch(header("@shipworthy/openapi-standard-schema"));
  expect(stdin.success, stdin.stderr).toBe(true);
  expect(stampLine.exec(stdin.stdout)?.[1]).toBe(stampLine.exec(typescript)?.[1]);
});
