import { execFileSync } from "node:child_process";
import { cpSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, beforeEach, expect, test } from "vitest";

const bin = new URL("../src/bin.ts", import.meta.url).pathname;
const stampLine = /^ \* (@shipworthy\/openapi-typescript@\S+:[0-9a-f]{64})$/m;

const spec = (title: string) =>
  JSON.stringify({
    openapi: "3.1.0",
    info: { title, version: "1.0.0" },
    paths: {
      "/pets": {
        get: {
          operationId: "listPets",
          responses: { "200": { description: "OK" } },
        },
      },
    },
  });

let dir: string;

beforeEach(() => {
  dir = mkdtempSync(join(tmpdir(), "openapi-cli-"));
});

afterEach(() => {
  rmSync(dir, { recursive: true, force: true });
});

function generate(input: string, ...flags: string[]) {
  return execFileSync(
    "bun",
    [bin, "generate", "tanstack-query", input, "-o", "out", "--name", "pets", ...flags],
    { cwd: dir, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] },
  );
}

const typesPath = () => join(dir, "out/pets/types.ts");
const stampOf = () => stampLine.exec(readFileSync(typesPath(), "utf8"))?.[1];

function markTypes() {
  writeFileSync(typesPath(), `${readFileSync(typesPath(), "utf8")}// marker\n`);
}

const isMarked = () => readFileSync(typesPath(), "utf8").includes("// marker");

const header = (name: string) =>
  new RegExp(
    `^/\\*\\*\\n \\* This file was auto-generated by ${name}\\.\\n \\* Do not make direct changes to the file\\.\\n \\*\\n \\* ${name}@0\\.0\\.1:[0-9a-f]{64}\\n \\*/\\n\\n`,
  );

test("records each generator's version and the schema hash in the comment header", () => {
  writeFileSync(join(dir, "a.json"), spec("Pets"));
  generate("a.json");

  expect(readFileSync(typesPath(), "utf8")).toMatch(header("@shipworthy/openapi-typescript"));
  expect(readFileSync(typesPath(), "utf8")).toContain("}\n\nexport type webhooks");

  expect(readFileSync(join(dir, "out/pets/client.ts"), "utf8")).toMatch(
    header("@shipworthy/openapi-tanstack-query-utils"),
  );
});

test("skips types.ts when the contents match, wherever the source lives", () => {
  writeFileSync(join(dir, "a.json"), spec("Pets"));
  generate("a.json");
  const stamp = stampOf();
  markTypes();

  cpSync(join(dir, "a.json"), join(dir, "b.json"));
  generate(join(dir, "b.json"));

  expect(isMarked()).toBe(true);
  expect(stampOf()).toBe(stamp);
});

test("regenerates types.ts when the contents change", () => {
  writeFileSync(join(dir, "a.json"), spec("Pets"));
  generate("a.json");
  const stamp = stampOf();
  markTypes();

  writeFileSync(join(dir, "a.json"), spec("More pets"));
  generate("a.json");

  expect(isMarked()).toBe(false);
  expect(stampOf()).not.toBe(stamp);
});

test("--force regenerates types.ts when the contents match", () => {
  writeFileSync(join(dir, "a.json"), spec("Pets"));
  generate("a.json");
  const stamp = stampOf();
  markTypes();

  generate("a.json", "--force");

  expect(isMarked()).toBe(false);
  expect(stampOf()).toBe(stamp);
});

test("typescript and standard-schema outputs carry a stamped header", () => {
  writeFileSync(join(dir, "a.json"), spec("Pets"));

  const run = (...args: string[]) =>
    execFileSync("bun", [bin, "generate", ...args], { cwd: dir, encoding: "utf8" });

  expect(run("typescript", "a.json")).toMatch(header("@shipworthy/openapi-typescript"));

  expect(run("standard-schema", "a.json")).toMatch(header("@shipworthy/openapi-standard-schema"));

  const stdin = execFileSync("bun", [bin, "generate", "typescript"], {
    cwd: dir,
    encoding: "utf8",
    input: spec("Pets"),
  });

  expect(stampLine.exec(stdin)?.[1]).toBe(stampLine.exec(run("typescript", "a.json"))?.[1]);
});
