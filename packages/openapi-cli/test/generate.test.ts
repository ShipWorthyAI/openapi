const header = (name: string, camelCase = false) =>
  new RegExp(
    `^/\\*\\*\\n \\* This file was auto-generated by ${name}\\.\\n \\* Do not make direct changes to the file\\.\\n \\*\\n \\* ${name}@\\d+\\.\\d+\\.\\d+(?:-[0-9A-Za-z.-]+)?:[0-9a-f]{64}\\n${camelCase ? " \\* Field casing: camelCase\\n" : ""} \\*/\\n\\n`,
  );

function setup(context: TestContext, spec: object = pets()) {
  const cli = workspace(context);

  const write = (file: string, value: object) =>
    writeFileSync(join(cli.dir, file), JSON.stringify(value));

  write("a.json", spec);

  return {
    ...cli,
    write,
    read: (file: string) => readFileSync(join(cli.dir, file), "utf8"),
    exists: (file: string) => existsSync(join(cli.dir, file)),
    files: (directory: string) => readdirSync(join(cli.dir, directory)).sort(),
    /** Every file in `directory` with its contents. */
    snapshot: (directory: string) =>
      Object.fromEntries(
        readdirSync(join(cli.dir, directory))
          .sort()
          .map((file) => [file, readFileSync(join(cli.dir, directory, file), "utf8")]),
      ),
  };
}

test("writes every plugin's files into one directory with camelCase and wire types", async (context) => {
  const { expect } = context;
  const cli = setup(context, reservations());

  const args = ["-i", "a.json", "-o", "out/reservations", "--camel-case", "--wire-types"];
  await cli.ok("generate", "zod", "tanstack-query", ...args);

  expect(cli.files("out/reservations")).toEqual([
    "client.ts",
    "types.ts",
    "wire-types.ts",
    "zod-schema.ts",
  ]);

  const types = cli.read("out/reservations/types.ts");
  expect(types).toMatch(header("@shipworthy/openapi-typescript", true));
  expect(types).toContain("partySize: number;");
  expect(types).not.toContain("party_size");

  const wire = cli.read("out/reservations/wire-types.ts");
  expect(wire).toMatch(header("@shipworthy/openapi-typescript"));
  expect(wire).toContain("party_size: number;");
  expect(wire).not.toContain("partySize");
  expect(wire).not.toContain("Field casing");

  const zod = cli.read("out/reservations/zod-schema.ts");
  expect(zod).toMatch(header("@shipworthy/openapi-zod", true));
  expect(zod).toContain('"partySize"');
  expect(zod).toContain('"specialRequests"');
  expect(zod).not.toContain("party_size");
  expect(zod).not.toContain("special_requests");

  const client = cli.read("out/reservations/client.ts");
  expect(client).toMatch(header("@shipworthy/openapi-tanstack-query", true));
  expect(client).toContain("export const createReservationsApiClient");
  expect(client).toContain("createApiClient<paths>({ ...options, caseMapping })");
  expect(client).toMatch(/"party_size": \{\s*"name": "partySize"/);
});

test("plugin order and duplicates do not change the output", async (context) => {
  const { expect } = context;
  const cli = setup(context, reservations());

  const orders = [
    ["zod", "tanstack-query"],
    ["tanstack-query", "zod"],
    ["zod", "zod", "tanstack-query"],
  ];

  await Promise.all(
    orders.map((plugins, index) =>
      cli.ok("generate", ...plugins, "-i", "a.json", "-o", `out/${index}/reservations`),
    ),
  );

  const [first, ...rest] = orders.map((_, index) => cli.snapshot(`out/${index}/reservations`));
  expect(Object.keys(first ?? {})).toEqual(["client.ts", "types.ts", "zod-schema.ts"]);
  for (const snapshot of rest) expect(snapshot).toEqual(first);
});

test("plugins sharing one model do not see each other's changes to it", async (context) => {
  const { expect } = context;
  const cli = setup(context, discriminated);

  await Promise.all([
    cli.ok("generate", "typescript", "zod", "-i", "a.json", "-o", "out/both"),
    cli.ok("generate", "zod", "-i", "a.json", "-o", "out/zod"),
  ]);

  const zod = cli.read("out/zod/zod-schema.ts");
  expect(cli.read("out/both/zod-schema.ts")).toBe(zod);
  // The typescript plugin adds discriminator enums to its own copy of the model only.
  expect(cli.read("out/zod/types.ts")).toContain("added by openapi-typescript");
  expect(zod).not.toContain("added by openapi-typescript");
});

test("--validation-middleware adds openapi-fetch middleware to plugins that support it", async (context) => {
  const { expect } = context;
  const cli = setup(context, reservations());

  const run = (output: string, ...args: string[]) =>
    cli.ok("generate", ...args, "-i", "a.json", "-o", `out/${output}`);

  await Promise.all([
    run("plain", "zod", "standard-schema"),
    run("both", "zod", "standard-schema", "--validation-middleware"),
    run("zod", "zod", "--validation-middleware"),
    run("typescript", "typescript", "--validation-middleware"),
  ]);

  const read = (output: string, file: string) => cli.read(`out/${output}/${file}`);

  for (const file of ["zod-schema.ts", "standard-schema.ts"]) {
    expect(read("plain", file)).not.toContain("onRequestValidation");
    expect(read("both", file)).toContain("export async function onRequestValidation(");
    expect(read("both", file)).toContain("export async function onResponseValidation(");
  }

  expect(read("zod", "zod-schema.ts")).toBe(read("both", "zod-schema.ts"));
  expect(cli.files("out/zod")).toEqual(["types.ts", "zod-schema.ts"]);
  // typescript has no middleware, so the flag changes nothing.
  expect(cli.files("out/typescript")).toEqual(["types.ts"]);
  expect(read("typescript", "types.ts")).toBe(read("plain", "types.ts"));
  expect(read("both", "types.ts")).toBe(read("plain", "types.ts"));
});

