test("--check compares every file without writing", async (context) => {
  const { expect } = context;
  const cli = setup(context);
  const args = ["generate", "zod", "tanstack-query", "-i", "a.json", "-o", "out/pets"];
  await cli.ok(...args);
  const generated = cli.snapshot("out/pets");

  expect(await cli.ok(...args, "--check")).toBe("");
  expect(cli.snapshot("out/pets")).toEqual(generated);

  writeFileSync(join(cli.dir, "out/pets/types.ts"), `${generated["types.ts"]}// edited\n`);
  rmSync(join(cli.dir, "out/pets/zod-schema.ts"));

  expect(await cli.fails(...args, "--check")).toMatch(
    /Generated files are not up-to-date: types\.ts, zod-schema\.ts$/m,
  );

  expect(cli.files("out/pets")).toEqual(["client.ts", "types.ts"]);
  expect(cli.read("out/pets/types.ts")).toBe(`${generated["types.ts"]}// edited\n`);

  await cli.ok(...args);
  cli.write("a.json", pets("More pets"));

  expect(await cli.fails(...args, "--check")).toMatch(
    /Generated files are not up-to-date: client\.ts, types\.ts, zod-schema\.ts$/m,
  );

  expect(cli.snapshot("out/pets")).toEqual(generated);
});

