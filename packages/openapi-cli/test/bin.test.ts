import { readdirSync } from "node:fs";
import { join } from "node:path";
import { test } from "vitest";
import { workspace } from "./cli.ts";

test("bin.ts runs the CLI with Node services and loads generators", async (context) => {
  const { expect } = context;
  const cli = workspace(context, { spawn: true });

  const result = await cli.run(["generate", "typescript"], {
    stdin: JSON.stringify({
      openapi: "3.1.0",
      info: { title: "Pets", version: "1" },
      paths: {
        "/pets": { get: { operationId: "listPets", responses: { "200": { description: "OK" } } } },
      },
    }),
  });

  expect(result.success, result.stderr).toBe(true);
  expect(result.stdout).toContain("auto-generated by @shipworthy/openapi-typescript");
  expect(result.stdout).toContain('listPets = "/pets"');
});

test("bin.ts writes several plugins' files from stdin", async (context) => {
  const { expect } = context;
  const cli = workspace(context, { spawn: true });

  const result = await cli.run(["generate", "zod", "tanstack-query", "-o", "out/pets"], {
    stdin: JSON.stringify({
      openapi: "3.1.0",
      info: { title: "Pets", version: "1" },
      paths: {
        "/pets": { get: { operationId: "listPets", responses: { "200": { description: "OK" } } } },
      },
    }),
  });

  expect(result.success, result.stderr).toBe(true);
  expect(result.stdout).toContain("stdin → out/pets/client.ts");

  expect(readdirSync(join(cli.dir, "out/pets")).sort()).toEqual([
    "client.ts",
    "types.ts",
    "zod-schema.ts",
  ]);
});

test("bin.ts exits non-zero when a command fails", async (context) => {
  const { expect } = context;
  const cli = workspace(context, { spawn: true });
  expect(await cli.fails("generate", "typescript", "--unknown-option")).toMatch(/unknown-option/);
});
