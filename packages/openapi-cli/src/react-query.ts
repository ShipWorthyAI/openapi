import { Effect } from "effect";
import { Command } from "effect/unstable/cli";
import openapiTS from "@shipworthy/openapi-typescript";
import { clientFlags, requireClientName, schemaUrl, writeClient } from "./client-files";
import { pascalCase, prefixTypes } from "./prefix-types";
import { userError } from "./user-error";

const hooks = ["Query", "QueryOptions", "SuspenseQuery", "InfiniteQuery", "Mutation"] as const;

function clientSource(prefix: string): string {
  const paths = `${prefix}ApiPaths`;
  return `// Generated by openapi-react-query. Do not edit.
import {
  createApiClient,
  useApiClient,
${hooks.map((hook) => `  useApiClient${hook},`).join("\n")}
} from "@shipworthy/openapi-react-query";
import type { ${paths} } from "./types";

export type { ${paths}, ${prefix}ApiComponents, ${prefix}ApiOperations } from "./types";
export { ApiClientProvider as ${prefix}ApiClientProvider } from "@shipworthy/openapi-react-query";

export const create${prefix}ApiClient: typeof createApiClient<${paths}> = createApiClient<${paths}>;
export type ${prefix}ApiClient = ReturnType<typeof create${prefix}ApiClient>;
export const use${prefix}ApiClient: typeof useApiClient<${paths}> = useApiClient<${paths}>;

${hooks
  .map(
    (hook) => `export const use${prefix}${hook}: ReturnType<typeof useApiClient${hook}<${paths}>> =
  useApiClient${hook}<${paths}>();`,
  )
  .join("\n")}
`;
}

export const reactQuery = Command.make("react-query", clientFlags(), ({ name, output, schema }) =>
  Effect.gen(function* () {
    yield* requireClientName(name);
    const document = yield* schemaUrl(schema);
    const nodes = yield* Effect.tryPromise({
      try: () => openapiTS(document),
      catch: (cause) => userError(cause),
    });
    const prefix = pascalCase(name);
    const types = yield* Effect.try({
      try: () => prefixTypes(nodes, prefix),
      catch: (cause) => userError(cause),
    });
    yield* writeClient(output, name, types, clientSource(prefix));
  }),
).pipe(
  Command.withDescription("Generate a typed React Query client from an OpenAPI schema."),
  Command.withShortDescription("Generate a React Query client"),
  Command.withExamples([
    {
      command:
        "openapi react-query http://api.shipworthy.localhost/docs/todos.openapi.json -o ./src/generated --name todos",
      description: "Write todos/types.ts and todos/client.ts",
    },
  ]),
);
