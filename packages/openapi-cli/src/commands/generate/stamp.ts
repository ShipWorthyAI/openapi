import { fileURLToPath } from "node:url";
import { Effect, FileSystem, Option, Path, Schema } from "effect";
import { CliError } from "effect/cli";
import { Digest } from "effect/crypto";

const PackageJson = Schema.Struct({ name: Schema.String, version: Schema.String });

interface Stamp {
  readonly name: string;
  readonly stamp: string;
}

/**
 * `<package>@<version>:<sha256 of the schema text>` for the generator at `specifier`.
 * camelCase output hashes the text with a casing marker, so toggling the flag changes the stamp.
 */
export const generatorStamp = Effect.fn("generatorStamp")(function* (
  specifier: string,
  text: string,
  camelCase: boolean,
) {
  const generator = yield* generatorPackage(specifier);
  const hash = yield* sha256(camelCase ? `${text}\0camel-case` : text);
  return { name: generator.name, stamp: `${generator.name}@${generator.version}:${hash}` };
});

export function fileHeader(generator: Stamp, camelCase: boolean): string {
  const casingLine = camelCase ? " * Field casing: camelCase\n" : "";

  return `/**
 * This file was auto-generated by ${generator.name}.
 * Do not make direct changes to the file.
 *
 * ${generator.stamp}
${casingLine} */
\n`;
}

const generatorPackage = Effect.fn("generatorPackage")(function* (specifier: string) {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const name = specifier.split("/", specifier.startsWith("@") ? 2 : 1).join("/");

  const resolved = yield* Effect.try({
    try: () => fileURLToPath(import.meta.resolve(specifier)),
    catch: (cause) => new CliError.UserError({ cause }),
  });

  for (let directory = path.dirname(resolved); ; directory = path.dirname(directory)) {
    const text = yield* fs.readFileString(path.join(directory, "package.json")).pipe(Effect.option);

    if (Option.isSome(text)) {
      const decoded = yield* Schema.decodeEffect(Schema.fromJsonString(PackageJson))(
        text.value,
      ).pipe(Effect.option);

      if (Option.isSome(decoded) && decoded.value.name === name) return decoded.value;
    }

    if (path.dirname(directory) === directory) {
      return yield* new CliError.UserError({ cause: `Cannot find package.json for ${name}.` });
    }
  }
});

const sha256 = Effect.fn("sha256")(function* (text: string) {
  const digest = yield* Digest.Digest;
  return yield* digest.digestHex(Digest.sha256, new TextEncoder().encode(text));
});
